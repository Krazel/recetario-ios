import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {requireAltoolSuccess} from './altool-result.mjs';

const cfg = JSON.parse(fs.readFileSync('ios/testflight.json'));
assert(!cfg.distributionBlocked, cfg.distributionBlocked);
assert(process.platform === 'darwin' && process.env.RECETARIO_DISTRIBUTION === 'testflight', 'Explicit macOS TestFlight environment required');
assert(process.env.RUNNER_TEMP, 'RUNNER_TEMP required');
const temp = fs.mkdtempSync(path.join(process.env.RUNNER_TEMP, 'recetario-signing-'));
const run = (command, args, options = {}) => {
  const result = spawnSync(command, args, {stdio: 'inherit', ...options});
  if (result.status !== 0) throw new Error(`${command} failed (${result.status})`);
  return result;
};
const readPlist = file => JSON.parse(run('python3', ['-c', 'import plistlib,json,sys; print(json.dumps(plistlib.load(open(sys.argv[1],"rb")),default=str))', file], {encoding:'utf8',stdio:'pipe'}).stdout);
const decode = (key, file) => {
  assert(process.env[key], `Missing ${key}`);
  fs.writeFileSync(file, Buffer.from(process.env[key], 'base64'), {mode:0o600});
};
const keychain = path.join(temp, 'signing.keychain-db');
const certificate = path.join(temp, 'distribution.p12');
const profile = path.join(temp, 'app.mobileprovision');
const profilePlist = path.join(temp, 'profile.plist');
const keyDir = path.join(process.env.HOME, '.appstoreconnect', 'private_keys');
assert(/^[A-Z0-9]{10}$/.test(process.env.ASC_KEY_ID || ''), 'Invalid key ID');
const apiKeyPath = path.join(keyDir, `AuthKey_${process.env.ASC_KEY_ID}.p8`);
const password = crypto.randomBytes(24).toString('hex');
let installedProfile;
try {
  decode('IOS_DISTRIBUTION_P12_BASE64', certificate);
  decode('IOS_APP_STORE_PROFILE_BASE64', profile);
  fs.mkdirSync(keyDir, {recursive:true});
  decode('ASC_PRIVATE_KEY_BASE64', apiKeyPath);
  run('security', ['cms', '-D', '-i', profile, '-o', profilePlist]);
  const provision = readPlist(profilePlist);
  assert.equal(provision.Entitlements['application-identifier'], `${cfg.teamId}.${cfg.bundleId}`);
  assert.equal(provision.Entitlements['get-task-allow'], false);
  assert.equal(provision.Entitlements['beta-reports-active'], true);
  assert(Date.parse(provision.ExpirationDate) > Date.now(), 'Expired profile');
  const profiles = path.join(process.env.HOME, 'Library', 'MobileDevice', 'Provisioning Profiles');
  fs.mkdirSync(profiles, {recursive:true});
  installedProfile = path.join(profiles, `${provision.UUID}.mobileprovision`);
  fs.copyFileSync(profile, installedProfile);
  run('security', ['create-keychain', '-p', password, keychain]);
  run('security', ['set-keychain-settings', '-lut', '21600', keychain]);
  run('security', ['unlock-keychain', '-p', password, keychain]);
  run('security', ['import', certificate, '-k', keychain, '-P', process.env.IOS_DISTRIBUTION_P12_PASSWORD, '-T', '/usr/bin/codesign', '-T', '/usr/bin/security']);
  run('security', ['list-keychains', '-d', 'user', '-s', keychain]);
  run('security', ['set-key-partition-list', '-S', 'apple-tool:,apple:,codesign:', '-s', '-k', password, keychain]);
  run('xcodegen', ['generate'], {cwd:'ios'});
  const archive = path.join(temp, 'Recetario.xcarchive');
  run('xcodebuild', ['archive', '-project', 'ios/Recetario.xcodeproj', '-scheme', 'Recetario', '-configuration', 'Release', '-destination', 'generic/platform=iOS', '-archivePath', archive, 'ARCHS=arm64', 'ONLY_ACTIVE_ARCH=NO', 'CODE_SIGN_STYLE=Manual', `DEVELOPMENT_TEAM=${cfg.teamId}`, 'CODE_SIGN_IDENTITY=Apple Distribution', `PROVISIONING_PROFILE_SPECIFIER=${provision.Name}`]);
  const app = path.join(archive, 'Products', 'Applications', 'Recetario.app');
  const info = readPlist(path.join(app, 'Info.plist'));
  assert.equal(info.CFBundleIdentifier, cfg.bundleId);
  assert.equal(info.CFBundleShortVersionString, cfg.marketingVersion);
  assert.equal(String(info.CFBundleVersion), cfg.buildNumber);
  assert.equal(info.ITSAppUsesNonExemptEncryption, false);
  assert(Number(info.DTSDKName.match(/\d+/)[0]) >= 26, 'iOS 26 SDK required');
  assert(fs.existsSync(path.join(app, 'PrivacyInfo.xcprivacy')), 'Missing privacy manifest');
  run('codesign', ['--verify', '--deep', '--strict', app]);
  const options = path.join(temp, 'ExportOptions.plist');
  run('python3', ['-c', 'import plistlib,json,sys; plistlib.dump(json.load(sys.stdin),open(sys.argv[1],"wb"))', options], {input:JSON.stringify({method:'app-store-connect',destination:'export',teamID:cfg.teamId,signingStyle:'manual',signingCertificate:'Apple Distribution',provisioningProfiles:{[cfg.bundleId]:provision.Name},manageAppVersionAndBuildNumber:false,uploadSymbols:true,stripSwiftSymbols:true}),stdio:['pipe','inherit','inherit']});
  const output = path.join(temp, 'export');
  run('xcodebuild', ['-exportArchive', '-archivePath', archive, '-exportOptionsPlist', options, '-exportPath', output]);
  const ipa = path.join(output, fs.readdirSync(output).find(name => name.endsWith('.ipa')));
  fs.mkdirSync('artifacts/testflight', {recursive:true});
  const artifact = `artifacts/testflight/Recetario-${cfg.marketingVersion}-build${cfg.buildNumber}-TestFlight.ipa`;
  fs.copyFileSync(ipa, artifact);
  const manifest = {app:'Recetario',purpose:'TestFlight',version:cfg.marketingVersion,build:cfg.buildNumber,bundleId:cfg.bundleId,appId:cfg.appId,commit:process.env.GITHUB_SHA,run:process.env.GITHUB_RUN_ID,sha256:crypto.createHash('sha256').update(fs.readFileSync(artifact)).digest('hex'),bytes:fs.statSync(artifact).size,sdk:info.DTSDKName,signatureVerified:true};
  manifest.appIconSourceSHA256 = crypto.createHash('sha256').update(fs.readFileSync('ios/Recetario/Assets.xcassets/AppIcon.appiconset/AppIcon.png')).digest('hex');
  manifest.compiledAssetsSHA256 = crypto.createHash('sha256').update(fs.readFileSync(path.join(app, 'Assets.car'))).digest('hex');
  const save = () => fs.writeFileSync('artifacts/testflight/build.json', JSON.stringify(manifest,null,2)+'\n');
  save(); console.log("RECETARIO_PACKAGE_RECEIPT="+JSON.stringify(manifest));
  const deliver = operation => {
    const result = spawnSync('xcrun', ['altool', `--${operation}-app`, '--type', 'ios', '--file', artifact, '--apiKey', process.env.ASC_KEY_ID, '--apiIssuer', process.env.ASC_ISSUER_ID], {encoding:'utf8', maxBuffer:16*1024*1024});
    process.stdout.write(result.stdout || '');
    process.stderr.write(result.stderr || '');
    return requireAltoolSuccess(result, operation);
  };
  deliver('validate');
  manifest.deliveryId = deliver('upload');
  manifest.uploadAccepted = true; console.log("RECETARIO_UPLOAD_RECEIPT="+JSON.stringify(manifest));
  save();
} finally {
  spawnSync('security', ['delete-keychain', keychain], {stdio:'ignore'});
  for (const file of [certificate, profile, profilePlist, apiKeyPath, installedProfile].filter(Boolean)) fs.rmSync(file, {force:true});
}
